// Fetches the reminder verses by surah:ayah (Tanzil Uthmani text, Sahih International) from the
// Al Quran Cloud API and writes src/features/reminder/verseData.ts. Run: node scripts/make-verses.js
const fs = require('fs');
const path = require('path');

const PASSAGES = [
  { id: '23:9-11', kind: 'reward', surah: 23, from: 9, to: 11 },
  { id: '2:277', kind: 'reward', surah: 2, from: 277, to: 277 },
  { id: '74:42-43', kind: 'warning', surah: 74, from: 42, to: 43 },
  { id: '107:4-5', kind: 'warning', surah: 107, from: 4, to: 5 },
  { id: '19:59', kind: 'warning', surah: 19, from: 59, to: 59 },
];

async function ayah(surah, number, edition) {
  const res = await fetch(`https://api.alquran.cloud/v1/ayah/${surah}:${number}/${edition}`);
  if (!res.ok) throw new Error(`${surah}:${number} ${edition} ${res.status}`);
  const json = await res.json();
  return json.data.text.trim();
}

async function passage({ id, kind, surah, from, to }) {
  const numbers = Array.from({ length: to - from + 1 }, (_, i) => from + i);
  const arabic = await Promise.all(numbers.map((n) => ayah(surah, n, 'quran-uthmani')));
  const english = await Promise.all(numbers.map((n) => ayah(surah, n, 'en.sahih')));
  return { id, kind, arabic: arabic.join(' ').replace(/^\u06de\s*/, ''), translation: english.join(' '), reference: `Quran ${id} · Sahih International` };
}

(async () => {
  const verses = [];
  for (const p of PASSAGES) verses.push(await passage(p));
  const body = `// Generated by scripts/make-verses.js from the Al Quran Cloud API (Tanzil Uthmani text, Sahih International).
// Placeholders until a scholar verifies them. Do not edit by hand.
export type VerseKind = 'reward' | 'warning';

export interface Verse {
  id: string;
  kind: VerseKind;
  arabic: string;
  translation: string;
  reference: string;
}

export const VERSES: readonly Verse[] = ${JSON.stringify(verses, null, 2)};
`;
  const out = path.join(__dirname, '..', 'src', 'features', 'reminder', 'verseData.ts');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, body);
  console.log('wrote', out);
})();
